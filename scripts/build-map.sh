#!/usr/bin/env bash
# Rebuilds map-data.js from Natural Earth's 1:50m countries.
# Usage: scripts/build-map.sh [natural-earth-tag]   (needs curl + node/npx)
set -euo pipefail

NE_TAG="${1:-v5.1.2}"
MAPSHAPER="mapshaper@0.7.61"
SRC="https://raw.githubusercontent.com/nvkelso/natural-earth-vector/${NE_TAG}/geojson/ne_50m_admin_0_countries.geojson"
OUT="$(cd "$(dirname "$0")/.." && pwd)/map-data.js"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

curl -fsSL "$SRC" -o "$TMP/ne.geojson"

# Natural Earth's default view shows de facto control; use internationally recognized borders instead:
# - Crimea is drawn with Russia; move it to Ukraine
# - Morocco includes Western Sahara west of the berm; give everything south of 27°40'N back to Western Sahara
WS_BOX="-18,20,-8,27.6667"
npx -y "$MAPSHAPER" -i "$TMP/ne.geojson" name=countries \
  -filter 'NAME !== "Antarctica"' \
  -each 'id = ISO_N3 !== "-99" ? ISO_N3 : (ISO_N3_EH !== "-99" ? ISO_N3_EH : null); name = NAME; k = ADM0_A3' \
  -filter-fields id,name,k \
  -explode \
  -each 'if (k === "RUS" && this.centroidX > 32 && this.centroidX < 37 && this.centroidY > 44 && this.centroidY < 46.5) { k = "UKR"; id = "804"; name = "Ukraine"; }' \
  -filter 'k === "MAR"' + name=ma_south \
  -filter 'k === "MAR"' target=countries + name=ma_north \
  -filter 'k !== "MAR"' target=countries \
  -clip bbox=$WS_BOX target=ma_south \
  -each 'k = "SAH"; id = "732"; name = "W. Sahara"' target=ma_south \
  -erase bbox=$WS_BOX target=ma_north \
  -merge-layers target=countries,ma_north,ma_south name=countries force \
  -dissolve k copy-fields=id,name \
  -filter-fields id,name \
  -o format=topojson id-field=id quantization=100000 "$TMP/countries.json"

{
  echo "// Generated by scripts/build-map.sh from Natural Earth ${NE_TAG} (public domain). Do not edit."
  printf 'window.COUNTRIES_TOPO = '
  cat "$TMP/countries.json"
  echo ';'
} > "$OUT"

echo "Wrote $OUT ($(wc -c < "$OUT" | tr -d ' ') bytes)"
